#: 名称 → (lon, lat, level)
#:
#: 去重是**必需的**（不是保洁）：手工维护的长列表很容易手滑写两遍
#: （实测 `神农架林区` 就重复过一次）。重复本身在 dict 里无害，
#: 但会让 `all_names()` 之类的下游出现重复项、也让测试的"无重名"断言变成噪音。
#: 这里**保留第一条**（列表是按"越具体越靠前"的顺序手工排的）。
GAZETTEER_INDEX: dict[str, tuple[float, float, str]] = {}
for _n, _lo, _la, _lv in GAZETTEER:
    GAZETTEER_INDEX.setdefault(_n, (_lo, _la, _lv))

#: 按名称**长度降序**的键列表，保证长名优先（"西双版纳" 先于 "西双"）。
#: 与 regions.py 同一套思路：短名抢长名是这类匹配最典型的翻车方式。
GAZETTEER_KEYS: list[str] = sorted(GAZETTEER_INDEX, key=len, reverse=True)

#: 级别 → AOI 半边长（度）
#:   province：约 ±1.2°（≈ 260 km 见方），省域通常是这个量级
#:   city    ：约 ±0.35°（≈ 78 km 见方），地级市市域的中位数
#: 刻意保守偏小 —— 框大了会把邻市并进来、统计被稀释；框小了至少还包含主城区。
LEVEL_HALF: dict[str, float] = {"province": 1.20, "city": 0.35}

#: 中国疆域经纬度包围盒（**含南海诸岛**，所以南界到 3.5°N）。
#: 用于守卫断言"坐标不能落到境外/远海"，别用更紧的框 —— `三沙市` 在 16.8°N，
#: 拿大陆的 18°N 去卡会把它误判成错误数据。
CHINA_BBOX = (73.0, 3.5, 135.5, 53.8)


def lookup(text: str) -> tuple[float, float, str] | None:
    """在坐标簿里找地名，返回 (lon, lat, level)，找不到返回 None。

    匹配策略与 `regions.get_region` 一致：**按名称长度降序做子串匹配**。
    这样 "西双版纳" 不会被更短的 "西双"（不存在，举例）抢走，
    而 "乌鲁木齐的植被" 也能命中 "乌鲁木齐"。
    """
    if not text:
        return None
    key = str(text).strip()
    for name in GAZETTEER_KEYS:
        if name in key:
            return GAZETTEER_INDEX[name]
    return None


def half_for(level: str) -> float:
    """按行政级别给出建议 AOI 半边长。未知级别按 city 处理（保守）。"""
    return LEVEL_HALF.get(level, LEVEL_HALF["city"])
