# ---------------------------------------------------------------------------
# 名称标准化与候选名（**必须定义在排序之前** —— 排序键依赖它们）
# ---------------------------------------------------------------------------
def normalize(name: str) -> str:
    """标准化地名：去空白、全角转半角、统一大小写。

    用户会输入「恩施 大峡谷」「恩施大峡谷 」这类带空格的形式，
    全角空格（U+3000）与普通空格都要处理掉，否则精确匹配会失败。
    """
    if not name:
        return ""
    s = str(name).strip()
    # 全角空格 / 制表符 / 换行
    s = re.sub(r"[\s\u3000]+", "", s)
    # 全角字符转半角（仅处理 ASCII 可映射区，中文不受影响）
    s = "".join(
        chr(ord(ch) - 0xFEE0) if 0xFF01 <= ord(ch) <= 0xFF5E else ch
        for ch in s
    )
    return s.lower()


def _candidates(r: dict) -> list[str]:
    """一条记录的所有可匹配名称（正式名 + 别名），供匹配与测试使用。"""
    return [r["name"], *r.get("aliases", [])]


def _sort_len(r: dict) -> int:
    """排序键 = 该条目**所有名称（含别名）里最长的那个**的长度。

    ⚠ 这里**不能**用 `len(r["name"])`（正式名长度）。因为匹配时别名与正式名等价，
    排序若只看正式名，"短别名 + 长正式名"的组合就会错位。

    实测过的侥幸组合（靠运气才对，不可依赖）：
      · `五大连池`(正式名 4 字) vs `大连市`(别名 `大连` 2 字)
      · `巴丹吉林沙漠`(6 字) vs `吉林市`(别名 `吉林` 2 字)
    只要往库里加一条正式名很短、别名很长的记录，排序就会把它排到后面，
    于是它的长别名抢不到本该属于它的输入。

    取"所有名称的最大长度"后，上述任意组合都稳定正确。
    """
    return max(len(normalize(c)) for c in _candidates(r))


