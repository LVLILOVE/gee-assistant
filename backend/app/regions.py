"""内置区域库：常见分析区域的中心坐标与建议范围，供离线兜底形成 AOI、前端快捷选择。

## 这个文件为什么这么长

2026-09-23 出过一类 bug：用户问「恩施大峡谷」的 NDVI，地图显示成苏州。
根因是**用区域名去查内置字典**，而字典只有 13 条 —— 恩施不在里面，
于是落到硬编码的太湖坐标兜底，图被画到了 1000 km 外。

「补几个地名」不是修复（下次问九寨沟、华山、三亚照样中招）。真正的修法是
让地图定位**不再依赖名字查表**（改为后端回传真实 AOI 边界）。但在下面这两处，
名字查表仍然是唯一的依据，所以库必须足够厚：

  1. `codegen._fallback_code` —— 大模型不可用时的兜底代码得有坐标才能画 AOI；
  2. 前端快捷选择 / 历史任务回填 —— 需要给用户「能直接点的地名」。

因此这里按「全国主要景区 + 山脉 + 湖泊河流 + 省会和主要城市」穷举到 **近 300 条**。
宁可长，不可缺：每缺一条，用户就会看到一次「定位不了」。

## 数据从哪里来（以及它的可靠边界）

坐标取自公开地理常识 + OpenStreetMap 地名数据，精度为**公里级**。
这对本项目**完全够用** —— AOI 最小也是 0.1°（约 11 km）见方的分析区，
公里级中心误差不会改变分析结论；但不要拿它当地籍测绘用。

⚠️ 地名是**唯一**的入库判据，坐标只精确到「这个点在该区域内部或紧邻」。
个别景区跨多个县、边界形状不规则，用中心点 + 半径近似即可，不追求贴合真实边界。

## 匹配规则（改 `get_center` 前必读）

  * 先**全等**匹配，再**子串**匹配；
  * 子串匹配按**名称长度降序**，所以「太湖流域」永远赢过「太湖」；
  * 但**反向**的坑要小心：地名 "太湖流域" 里包含 "太湖"，若不按长度排序，
    短的会抢走长的。同时「太湖」本身也必须能单独命中（用户就问"太湖"时）。
  * 所以：**凡是 A 是 B 的子串、且两者坐标不同的，都必须同时入库并依赖长度排序。**
    当前已覆盖的此类组合：太湖流域/太湖、长江三角洲/长三角。

## 别名

同一地点用户会写好几种（"黄山" / "黄山市" / "黄山风景区"）。
`aliases` 里的每个别名都会进匹配，等同于正式名。别名撞车时同样是长名优先。
"""

