"""默认日期区间的**唯一来源**。

## 为什么要有这个模块（2026-09-17）

产品里曾经散落着 8 处写死的年份，跨了后端 4 个模块 + 前端 2 个位置：

    app/intent.py   兜底 "2024-01-01" / "2024-12-31"，提示词"补全为 2025 年"
    app/planner.py  提示词"补全为 2025 年"
    app/codegen.py  生成代码里 or '2024-01-01' / or '2024-12-31'
    app/models.py   契约默认 2024-01-01 / 2024-12-31
    frontend/App.jsx 表单初始态 + 提交兜底 2024-01-01 / 2024-12-31

今天已是 2026 年 9 月，这些值全部过期一年以上。其中**最难查的一处是
`intent.py` 的兜底默认**：模型对模糊时间（用户只说"现在"）返回 null 本来是
**正确**行为，却会被这行 `or "2024-01-01"` 静默钉死在 2024 年——用户看到的
是"时间范围：2024-01-01 ~ 2024-12-31"，而错误不在模型，在这个兜底值。

所以默认区间必须集中到一处、并按当天日期推算，不再允许各模块自己写常量。

## 为什么默认取「最近一个完整自然年」

三种候选：

    A. 最近一个完整自然年  → 2025-01-01 ~ 2025-12-31
    B. 滚动最近 12 个完整月 → 2025-09-01 ~ 2026-08-31
    C. 今年年初至今        → 2026-01-01 ~ 2026-08-31

选 A，理由有三条：

1. **季节完整性**：遥感统计（NDVI 均值、水体面积）受物候影响极大。一个含四季
   的完整自然年才是有意义的统计口径；C 方案缺秋冬、会让 NDVI 系统性偏高。
2. **年内可复现**：A 在同一自然年内是常量，用户一月和十二月跑同一个需求得到
   同一个区间。B 每个月都在漂移，默认结果不可复现，没法做回归比对。
3. **语义连续性**：原实现就是一个完整自然年窗口，A 只是把"哪一年"从写死改成
   按当天推算，不改变产品的分析口径。

注意：A 只是**兜底**。用户明确说了"现在/最近一个月/6-8 月"时，由大模型解析出
具体区间，本模块不参与——所以不存在"用户问现在、却给他去年数据"的问题。
"""

from __future__ import annotations

from datetime import date


def today() -> date:
    """当天日期。单独包一层是为了让测试可以集中替换基准日。"""
    return date.today()


def today_iso() -> str:
    """当天日期（YYYY-MM-DD），用于往提示词里注入"今天是几号"。"""
    return today().isoformat()


def default_year() -> int:
    """默认分析年份 = 最近一个已经完整过去的自然年。

    1 月 1 日调用时返回去年，12 月 31 日调用时也返回去年——因为当年尚未结束，
    用它做年度统计会缺季节。
    """
    return today().year - 1


def default_start() -> str:
    """默认区间起始：最近一个完整自然年的 1 月 1 日。"""
    return f"{default_year()}-01-01"


def default_end() -> str:
    """默认区间结束：最近一个完整自然年的 12 月 31 日。"""
    return f"{default_year()}-12-31"


def default_range() -> tuple[str, str]:
    """默认区间 (起, 止)。等价于 (default_start(), default_end())。"""
    return default_start(), default_end()


def month_range_rule() -> str:
    """月份区间的补全规则——**返回完整句子，调用方直接嵌入，不要自己拼装**。

    刻意返回整条现成句子而不是一个词片段：这个规则要在 intent 和 planner 两处
    提示词里出现，若让调用方各自拼接前置从句，很容易拼成
    "只说了月份区间就若用户只说了月份区间（如 6-8 月）…" 这种重复句。

    措辞上刻意不说"补全为 XXXX 年"——那样等于把年份写死，明年就变成错误基准
    （这正是本次要修的 bug）。改成让模型按今天自己推算。
    """
    return (
        f"若用户只说了月份区间（如 6-8 月），补全为最近一个已经完整过去的"
        f"对应月份区间，不要补成未来的日期（今天是 {today_iso()}）"
    )
